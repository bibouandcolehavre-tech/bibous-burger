const SESSION_KEY = 'bibousCustomerSession';
const ATTEMPT_KEY = 'bibousPaymentAttempt';
const storage = () => globalThis.localStorage;
const {createSessionStorage}=require('./session-storage-queue');
const sessions=createSessionStorage({read:()=>storage()?.getItem(SESSION_KEY)||null,write:token=>storage().setItem(SESSION_KEY,token),clear:()=>storage()?.removeItem(SESSION_KEY)});
export const readSession = sessions.read;
export const saveSession = sessions.write;
export const clearSession = sessions.clear;
export const clearSessionIf = sessions.clearIf;
export const readAttempt = async () => storage()?.getItem(ATTEMPT_KEY) || null;
export const saveAttempt = async value => storage().setItem(ATTEMPT_KEY, JSON.stringify(value));
export const clearAttempt = async () => storage()?.removeItem(ATTEMPT_KEY);
